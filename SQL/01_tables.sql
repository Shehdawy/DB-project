
-- =========================================
-- 01_TABLES.SQL
-- Create all tables and primary keys
-- No foreign keys or additional constraints
-- =========================================


-- 1. CORPORATE GROUP
CREATE TABLE corporate_group (
    group_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_name VARCHAR(150) NOT NULL
);


-- 2. MARKET SEGMENT
CREATE TABLE market_segment (
    segment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    segment_name VARCHAR(100) NOT NULL
);


-- 3. GENDER
CREATE TABLE gender (
    gender_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gender_name VARCHAR(50) NOT NULL
);


-- 4. CONCENTRATION
CREATE TABLE concentration (
    concentration_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concentration_name VARCHAR(100) NOT NULL
);


-- 5. FRAGRANCE FAMILY
CREATE TABLE fragrance_family (
    family_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_name VARCHAR(100) NOT NULL
);


-- 6. ACCORD
CREATE TABLE accord (
    accord_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accord_name VARCHAR(100) NOT NULL
);


-- 7. NOTE
CREATE TABLE note (
    note_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    note_name VARCHAR(150) NOT NULL
);


-- 8. BRAND
CREATE TABLE brand (
    brand_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_name VARCHAR(150) NOT NULL,
    group_id INTEGER,
    segment_id INTEGER
);


-- 9. PERFUME
CREATE TABLE perfume (
    perfume_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(250) NOT NULL,
    release_year SMALLINT,
    rating_value NUMERIC(3,2),
    rating_count INTEGER,
    url TEXT,

    brand_id INTEGER,
    gender_id INTEGER,
    concentration_id INTEGER,
    family_id INTEGER
);


-- 10. PERFUME ACCORD
CREATE TABLE perfume_accord (
    perfume_id BIGINT NOT NULL,
    accord_id INTEGER NOT NULL,
    accord_rank INTEGER NOT NULL,

    PRIMARY KEY (perfume_id, accord_id)
);


-- 11. PERFUME NOTE
CREATE TABLE perfume_note (
    perfume_id BIGINT NOT NULL,
    note_id INTEGER NOT NULL,
    note_layer VARCHAR(20) NOT NULL,

    PRIMARY KEY (perfume_id, note_id, note_layer)
);
